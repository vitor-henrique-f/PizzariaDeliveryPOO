    private void btnEnviarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnviarActionPerformed

    int quantidade = 0;

    if (rBtn1sabor.isSelected()) {
        quantidade = 1;
    } else if (rBtn2sabor.isSelected()) {
        quantidade = 2;
    } else if (rBtn3sabor.isSelected()) {
        quantidade = 3;
    } else if (rBtn4sabor.isSelected()) {
        quantidade = 4;
    }

    if (quantidade == 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Selecione a quantidade de sabores.");
        return;
    }

    java.util.List<String> selecionados =
        new java.util.ArrayList<>();

    if (cBox4queijos.isSelected())
        selecionados.add("4 queijos");

    if (cBoxFranngoCatupiri.isSelected())
        selecionados.add("Frango e catupiri");

    if (cBoxCalabresa.isSelected())
        selecionados.add("Calabresa");

    if (cBoxBaskha.isSelected())
        selecionados.add("Baskha");

    if (cBoxMargarita.isSelected())
        selecionados.add("Margarita");

    if (selecionados.size() != quantidade) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Selecione exatamente " + quantidade
            + " sabor(es).");
        return;
    }

    cadastrarPedido(quantidade, selecionados);
}
        private void cadastrarPedido(
        int quantidade,
        java.util.List<String> selecionados) {

    String sqlPedido =
        "INSERT INTO pedidos (quantidade_sabores) VALUES (?)";

    String sqlSabor =
        "SELECT id_sabor FROM sabores WHERE nome = ?";

    String sqlItem =
        "INSERT INTO itens_pedido (id_pedido, id_sabor) "
        + "VALUES (?, ?)";

    // Substitua obterConexao() pelo método
    // de conexão que você já utiliza no projeto.
    try (java.sql.Connection con = conector()) {

        con.setAutoCommit(false);

        try {
            int idPedido;

            // Cadastra o pedido
            try (java.sql.PreparedStatement ps =
                    con.prepareStatement(
                        sqlPedido,
                        java.sql.Statement.RETURN_GENERATED_KEYS)) {

                ps.setInt(1, quantidade);
                ps.executeUpdate();

                try (java.sql.ResultSet rs =
                        ps.getGeneratedKeys()) {

                    if (!rs.next()) {
                        throw new java.sql.SQLException(
                            "Não foi possível obter o ID do pedido.");
                    }

                    idPedido = rs.getInt(1);
                }
            }

            // Cadastra os sabores associados ao pedido
            try (java.sql.PreparedStatement psSabor =
                    con.prepareStatement(sqlSabor);
                 java.sql.PreparedStatement psItem =
                    con.prepareStatement(sqlItem)) {

                for (String nome : selecionados) {

                    psSabor.setString(1, nome);

                    try (java.sql.ResultSet rs =
                            psSabor.executeQuery()) {

                        if (!rs.next()) {
                            throw new java.sql.SQLException(
                                "Sabor não encontrado: " + nome);
                        }

                        int idSabor = rs.getInt("id_sabor");

                        psItem.setInt(1, idPedido);
                        psItem.setInt(2, idSabor);
                        psItem.executeUpdate();
                    }
                }
            }

            con.commit();

            javax.swing.JOptionPane.showMessageDialog(
                this, "Pedido cadastrado com sucesso!");
            
            this.dispose();

        } catch (java.sql.SQLException e) {
            con.rollback();
            throw e;
        } finally {
            con.setAutoCommit(true);
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Erro ao cadastrar pedido: " + e.getMessage());
        
    }//GEN-LAST:event_btnEnviarActionPerformed
        }
    
    
